export const Route = createFileRoute("/legal/$doc")({
  head: ({ params }) => {
    const doc = DOCS[params.doc as DocKey] ?? { title: "Документ" };
    return {
      meta: [{ title: `${doc.title} — Баланс жизни` }, { name: "description", content: doc.title }],
    };
  },
  loader: ({ params }) => {
    if (!(params.doc in DOCS)) throw notFound();
    return null;
  },
  component: LegalPage,
  notFoundComponent: () => (
    <div className="mx-auto max-w-xl px-4 py-10 text-center text-sm text-muted-foreground">
      Документ не найден.{" "}
      <Link to="/" className="text-primary underline">
        На главную
      </Link>
    </div>
  ),
});

function LegalPage() {
  const { doc } = Route.useParams();
  const data = DOCS[doc as DocKey];

  return (
    <div className="min-h-screen w-full overflow-x-hidden bg-background px-4 py-6">
      <main className="mx-auto flex w-full max-w-2xl flex-col gap-5">
        <button
          type="button"
          onClick={() => window.history.back()}
          className="inline-flex w-fit items-center gap-2 text-sm text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="h-4 w-4" /> Назад
        </button>
        <div>
          <h1 className="text-2xl font-bold text-foreground">{data.title}</h1>
          <p className="mt-2 text-xs text-muted-foreground">
            Версия {LEGAL_DOCUMENT_VERSION} · действует с 7 октября 2026 года
          </p>
        </div>
        <Card className="p-5 sm:p-6">
          <div className="flex flex-col gap-5 text-sm leading-relaxed text-muted-foreground">
            <p className="text-foreground">{data.intro}</p>
            {data.sections.map((section) => (
              <section key={section.heading} className="flex flex-col gap-2">
                <h2 className="text-base font-semibold text-foreground">{section.heading}</h2>
                {section.paragraphs?.map((paragraph) => (
                  <p key={paragraph}>{paragraph}</p>
                ))}
                {section.items && (
                  <ul className="list-disc space-y-1 pl-5">
                    {section.items.map((item) => (
                      <li key={item}>{item}</li>
                    ))}
                  </ul>
                )}
              </section>
            ))}
          </div>
        </Card>
      </main>
    </div>
  );
}
